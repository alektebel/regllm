"""Materialise the 7-layer CICLOS_CALIBRADOS schema into SQLite.

A clean DB is generated by drawing *consistent* base attributes and then
re-applying the pipeline formulas from ``ciclos_calibrados_pipeline.sas``, so
that **every** oracle in ``defect_catalog`` returns 0 rows by construction.
For each defect, ``build_trap_conn`` appends a single mutated row (via the
defect's ``mutate``) so a non-empty query result is unambiguously caused by
that defect — the same mutation-testing contract as
``training/dq/dq_reward.py``.

Run directly to write a clean DB + per-defect trap DBs to ``data/``:

    python DQC/eval/generate_db.py --rows 2000
"""

from __future__ import annotations

import argparse
import math
import random
import sqlite3
from pathlib import Path

from defect_catalog import (
    DEFECTS, INT_COLS, PK_COLUMN, REAL_COLS, TABLE_NAME, Defect,
)

HERE = Path(__file__).resolve().parent
DATA_DIR = HERE / "data"

# Full ordered column list of the final table (see data_dictionary.md).
COLUMNS: list[str] = [
    # identity / segmentation
    "ID_CONTR_CICLO_LGD", "ID_CONTRATO", "ID_FUSION_FINAL", "SW_FUSION",
    "SEGMENTO", "CALIBRATION_SEGMENT", "PRODUCTO", "MES_CICLO",
    "ENTIDAD_ORIGEN",
    # exposure (BASILEA)
    "OR_EAD", "OR_DISPTO", "OR_DISBLE", "SALDO_PENDIENTE", "EAD",
    "EAD_BALANCE", "CCF_ESTIMADO", "EAD_FUERA_BALANCE", "EAD_TOTAL",
    # collateral
    "COLATERAL_TIPO", "VALOR_COLATERAL_INICIAL", "VALOR_COLATERAL",
    "HAIRCUT", "LTV",
    # PD
    "RATING_GRADO", "PD_ESTIMADA", "PD_SUELO", "PD_FINAL", "PD_DOWNTURN",
    # LGD
    "LGD_ESTIMADA", "LGD_REALIZADA", "LGD_SUELO", "MOC", "LGD_CON_MOC", "LGD_FINAL",
    # ECL / RWA / stage
    "K_IRB", "M_VENCIMIENTO", "RWA", "ECL", "PROVISION", "STAGE_IFRS9",
    # lifecycle / recovery
    "DPDS", "CURE_FLAG", "ESTADO_CICLO", "TERMINACION", "CAUSA_DEFAULT",
    "ADJUDICACION_FLAG", "ADJUDICACION_TIPO", "ADJUDICACION_VALOR",
    "RECUPERACION_ACUMULADA", "COSTE_TOTAL_ACUMULADO", "TASA_DESCUENTO",
    "TIPO_INTERES_ORIGINAL", "TIPO_INTERES_ACTUAL", "INTERESES_ACUMULADOS",
]

SEGMENTS = ["CORP", "SME", "RETAIL_HIP", "RETAIL_CONS"]
PRODUCTS = {"CORP": ["PRESTAMO", "LINEA"], "SME": ["PRESTAMO", "LINEA"],
            "RETAIL_HIP": ["HIPOTECA_LN"], "RETAIL_CONS": ["TARJETA", "PRESTAMO"]}
CAUSAS = ["90_DIAS_VENCIDO", "IMPROBABLE_PAGO", "REFINANCIACION_DETERIORO"]
TERMINACIONES = ["CURA", "FALLIDO", "VENTA_CARTERA", "LIQUIDACION"]
ADJ_TIPOS = ["SUBASTA", "DACCION", "SEGURO", "GARANTIA"]
ENTIDADES = ["BANCO_A", "BANCO_B", "BANCO_C"]
CCF = 0.75


def _type_of(col: str) -> str:
    if col in INT_COLS:
        return "INTEGER"
    if col in REAL_COLS:
        return "REAL"
    return "TEXT"


def create_table_sql(table: str = TABLE_NAME) -> str:
    defs = ", ".join(f'"{c}" {_type_of(c)}' for c in COLUMNS)
    return f'CREATE TABLE "{table}" ({defs})'


# ── consistent base generation ──────────────────────────────────────────────

def _base_row(rng: random.Random, idx: int) -> dict:
    """Draw internally-consistent base attributes (pre-derivation)."""
    seg = rng.choices(SEGMENTS, weights=[3, 3, 2, 2])[0]
    if seg == "RETAIL_HIP":
        colat = "HIPOTECA"
    elif seg == "CORP":
        colat = rng.choices(["NINGUNA", "PRENDA"], weights=[8, 2])[0]
    else:
        colat = rng.choices(["NINGUNA", "PRENDA"], weights=[9, 1])[0]

    contrato = f"CONT_{idx:06d}"
    fusion = rng.random() < 0.12
    sw_fusion = 1 if fusion else 0
    id_fusion = f"FUS_{idx:05d}" if fusion else None

    or_dispto = round(rng.uniform(8_000, 1_200_000), 2)
    or_disble = round(rng.uniform(0, 60_000), 2)
    or_ead = round(or_dispto + or_disble + rng.uniform(0, 500), 2)  # >= drawn

    # rating grade drawn first so PD can be banded by grade (monotonicity):
    # a worse grade must carry a higher PD (keeps D25 clean = 0).
    rating = rng.randint(1, 16)
    if rating <= 4:
        pd_band = (0.0006, 0.020)
    elif rating <= 8:
        pd_band = (0.010, 0.050)
    elif rating <= 12:
        pd_band = (0.030, 0.120)
    else:
        pd_band = (0.080, 0.180)
    pd_est = round(rng.uniform(*pd_band), 6)
    lgd_est = round(rng.uniform(0.05, 0.92), 6)

    dpds = rng.choices(
        [rng.randint(0, 29), rng.randint(30, 89), rng.randint(90, 400)],
        weights=[6, 2, 2],
    )[0]
    stage = 1 if dpds < 30 else 2 if dpds < 90 else 3

    cerrado = rng.random() < 0.4
    estado = "CERRADO" if cerrado else "ESTIMACION"
    terminacion = rng.choice(TERMINACIONES) if cerrado else ""

    adjud = rng.random() < 0.3
    if adjud:
        adj_flag, adj_tipo = "1", rng.choice(ADJ_TIPOS)
        adj_valor = round(rng.uniform(5_000, 80_000), 2)
    else:
        adj_flag, adj_tipo, adj_valor = "0", "", 0.0

    # collateral valuation only when secured
    if colat == "HIPOTECA":
        vcol_in = round(rng.uniform(120_000, 500_000), 2)
        haircut = round(rng.uniform(0.02, 0.08), 4)
    elif colat == "PRENDA":
        vcol_in = round(rng.uniform(10_000, 90_000), 2)
        haircut = round(rng.uniform(0.05, 0.15), 4)
    else:
        vcol_in, haircut = 0.0, 0.0

    ead_bal = or_dispto
    ead_total = ead_bal + CCF * or_disble
    recup = round(rng.uniform(0, 0.55) * ead_bal, 2)        # well under 1.5*EAD
    coste = round(rng.uniform(0, 0.08) * ead_bal, 2)

    period = (2019 + rng.randint(0, 4)) * 100 + rng.randint(1, 12)  # valid YYYYMM

    return {
        "ID_CONTR_CICLO_LGD": f"{contrato}_{period}",
        "ID_CONTRATO": contrato,
        "ID_FUSION_FINAL": id_fusion,
        "SW_FUSION": sw_fusion,
        "SEGMENTO": seg,
        "CALIBRATION_SEGMENT": f"{seg}_{rng.choice(['HIGH','MED','LOW','MICRO'])}",
        "PRODUCTO": rng.choice(PRODUCTS[seg]),
        "MES_CICLO": period,
        "ENTIDAD_ORIGEN": rng.choice(ENTIDADES),
        "OR_EAD": or_ead,
        "OR_DISPTO": or_dispto,
        "OR_DISBLE": or_disble,
        "SALDO_PENDIENTE": or_dispto,
        "COLATERAL_TIPO": colat,
        "VALOR_COLATERAL_INICIAL": vcol_in,
        "HAIRCUT": haircut,
        "RATING_GRADO": rating,
        "PD_ESTIMADA": pd_est,
        "LGD_ESTIMADA": lgd_est,
        "LGD_REALIZADA": round(rng.uniform(0.0, 0.95), 6),
        "STAGE_IFRS9": stage,
        "DPDS": dpds,
        "CURE_FLAG": 1 if (cerrado and rng.random() < 0.6) else 0,
        "ESTADO_CICLO": estado,
        "TERMINACION": terminacion,
        "CAUSA_DEFAULT": rng.choice(CAUSAS),
        "ADJUDICACION_FLAG": adj_flag,
        "ADJUDICACION_TIPO": adj_tipo,
        "ADJUDICACION_VALOR": adj_valor,
        "RECUPERACION_ACUMULADA": recup,
        "COSTE_TOTAL_ACUMULADO": coste,
        "TASA_DESCUENTO": round(rng.uniform(0.02, 0.08), 6),
        "TIPO_INTERES_ORIGINAL": round(rng.uniform(0.02, 0.12), 5),
        "TIPO_INTERES_ACTUAL": round(rng.uniform(0.02, 0.14), 5),
        "INTERESES_ACUMULADOS": round(rng.uniform(0, 8000), 2),
        # placeholders filled by derive()
        "EAD": None, "EAD_BALANCE": None, "EAD_FUERA_BALANCE": None,
        "EAD_TOTAL": None, "CCF_ESTIMADO": None, "LTV": None,
        "VALOR_COLATERAL": None, "PD_SUELO": None, "PD_FINAL": None,
        "PD_DOWNTURN": None, "LGD_SUELO": None, "MOC": None,
        "LGD_CON_MOC": None, "LGD_FINAL": None, "K_IRB": None,
        "M_VENCIMIENTO": None, "RWA": None, "ECL": None, "PROVISION": None,
    }


def derive(row: dict) -> dict:
    """Apply the 7-layer pipeline formulas to a base row (in place)."""
    r = dict(row)
    seg = r["SEGMENTO"]; colat = r["COLATERAL_TIPO"]
    pd_est = r["PD_ESTIMADA"]; lgd_est = r["LGD_ESTIMADA"]

    # L4 PD
    r["PD_SUELO"] = 0.0005 if seg == "RETAIL_HIP" else 0.0003
    r["PD_FINAL"] = max(pd_est, r["PD_SUELO"])
    r["PD_DOWNTURN"] = min(1.0, 1.5 * pd_est)
    # L5 LGD
    if colat == "HIPOTECA":
        lgd_suelo = 0.30
    elif seg == "CORP":
        lgd_suelo = 0.45
    else:
        lgd_suelo = 0.0
    r["LGD_SUELO"] = lgd_suelo
    moc = 0.05 * lgd_est
    r["MOC"] = moc
    r["LGD_CON_MOC"] = lgd_est + moc
    r["LGD_FINAL"] = max(r["LGD_CON_MOC"], lgd_suelo)
    # L6 EAD
    r["CCF_ESTIMADO"] = CCF
    r["EAD_BALANCE"] = r["OR_DISPTO"] if r["OR_DISPTO"] is not None else r["SALDO_PENDIENTE"]
    r["EAD_FUERA_BALANCE"] = CCF * (r["OR_DISBLE"] or 0.0)
    r["EAD_TOTAL"] = r["EAD_BALANCE"] + r["EAD_FUERA_BALANCE"]
    r["EAD"] = r["EAD_TOTAL"]
    # collateral derived
    vcol_in = r["VALOR_COLATERAL_INICIAL"] or 0.0
    hc = r["HAIRCUT"] or 0.0
    r["VALOR_COLATERAL"] = round(vcol_in * (1 - hc), 2)
    r["LTV"] = round(r["EAD_BALANCE"] / r["VALOR_COLATERAL"], 6) if r["VALOR_COLATERAL"] > 0 else 0.0
    # L7 ECL/RWA
    pdf = r["PD_FINAL"]; lgdf = r["LGD_FINAL"]; eadt = r["EAD_TOTAL"]
    r["K_IRB"] = math.sqrt(pdf) * 0.06 + pdf * 0.5
    r["M_VENCIMIENTO"] = min(5.0, max(1.0, 3.0)) if seg == "CORP" else 2.5
    r["RWA"] = eadt * lgdf * 12.5 * r["K_IRB"]
    r["ECL"] = pdf * lgdf * eadt
    r["PROVISION"] = r["ECL"]
    return r


def build_clean_conn(n_rows: int = 2000, seed: int = 42,
                     table: str = TABLE_NAME) -> sqlite3.Connection:
    """Build an in-memory clean DB with all invariants satisfied."""
    rng = random.Random(seed)
    conn = sqlite3.connect(":memory:", check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute(create_table_sql(table))
    placeholders = ", ".join(["?"] * len(COLUMNS))
    ins = f'INSERT INTO "{table}" VALUES ({placeholders})'
    batch = []
    for i in range(1, n_rows + 1):
        row = derive(_base_row(rng, i))           # derive ONCE per row
        batch.append([row.get(c) for c in COLUMNS])
        if len(batch) >= 1000:
            conn.executemany(ins, batch); batch.clear()
    if batch:
        conn.executemany(ins, batch)
    conn.commit()
    return conn


def build_trap_conn(defect: Defect, n_rows: int = 2000, seed: int = 42,
                    table: str = TABLE_NAME) -> sqlite3.Connection:
    """Clean DB + ONE row mutated by ``defect`` (fresh PK appended last)."""
    clean = build_clean_conn(n_rows, seed, table)
    # mutate a deterministic base row so the planted defect is reproducible
    rng = random.Random(seed + 7919)
    base = derive(_base_row(rng, 1_000_000))
    dirty = defect.mutate(base)
    dirty[PK_COLUMN] = f"__DIRTY_{defect.defect_id}__"
    placeholders = ", ".join(["?"] * len(COLUMNS))
    clean.execute(f'INSERT INTO "{table}" VALUES ({placeholders})',
                  [dirty.get(c) for c in COLUMNS])
    clean.commit()
    return clean


# ── CLI: dump clean + per-defect trap DBs to disk ───────────────────────────

def _dump(conn: sqlite3.Connection, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        path.unlink()
    sqlite3.connect(str(path)).executescript("")  # touch
    conn2 = sqlite3.connect(str(path))
    conn.backup(conn2)
    conn2.close()


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate the DQC eval databases.")
    ap.add_argument("--rows", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", type=Path, default=DATA_DIR)
    args = ap.parse_args()

    clean = build_clean_conn(args.rows, args.seed)
    _dump(clean, args.out / "clean.db")
    n = clean.execute(f"SELECT COUNT(*) FROM {TABLE_NAME}").fetchone()[0]
    print(f"clean.db  → {n} rows")

    for d in DEFECTS:
        trap = build_trap_conn(d, args.rows, args.seed)
        _dump(trap, args.out / f"trap_{d.defect_id}.db")
    print(f"Wrote {len(DEFECTS)} trap DBs (trap_<id>.db) to {args.out}/")


if __name__ == "__main__":
    main()
